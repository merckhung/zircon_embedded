#!/usr/bin/env python3
"""End-to-end QEMU verification of //minimal_rootfs:minimal_system.

Usage: verify_minimal.py <qemu> <boot_shim> <zbi> [--timeout SECONDS]

PASS requires, on the serial console:
  * [ZX_TEST: PASS]   printed by zx_test only after all of its checks pass.
  * For each conformance test in SUITES (//userland/tests mm_test and
    proc_test): its "[<TAG>: PASS n/n]" summary with n >= the minimum check
    count, and "<name> exit code: 0" from /init. Any "[<TAG>: FAIL" line
    fails. ("[restricted] ... (mm_test|proc_test) ..." exception lines are
    expected: the tests deliberately fault, in forked children or with
    handlers installed, to check real signal delivery.)
  * BUSYBOX PIPELINE OK  computed by /init via `tr a-z A-Z` (the script only
    contains the mixed-case input text).
  * After commands are typed into the interactive BusyBox shell over the
    serial port, the shell's *computed* outputs:
      INTERACTIVE_SHELL_TEST=42     from `echo ...=$((6 * 7))`
      SHELL_PIPE_ZIRCON             from `echo zircon | tr a-z A-Z | sed ...`
      the /proc/zircon/processes header (generated by the shim)
      BUSYBOX_SHELL_DONE_1337       from `echo ..._$((1000 + 337))`
    None of these strings occurs in the typed text, so the terminal echoing
    the input cannot satisfy them.
"""

import argparse
import os
import re
import select
import subprocess
import sys
import time

INTERACTIVE_SCRIPT = (
    b"echo INTERACTIVE_SHELL_TEST=$((6 * 7))\n"
    b"echo zircon | tr a-z A-Z | sed 's/^/SHELL_PIPE_/'\n"
    b"cat /proc/zircon/processes\n"
    b"echo BUSYBOX_SHELL_DONE_$((1000 + 337))\n"
)

# (binary name, summary tag, minimum number of checks)
SUITES = [
    ("mm_test", "MM_TEST", 49),
    ("proc_test", "PROC_TEST", 41),
]
SUITE_FAIL_RE = re.compile(
    rb"\[(?:" + b"|".join(t.encode() for _, t, _ in SUITES) + rb"): FAIL[^\r\n]*")

BOOT_CHECKS = [
    (b"[ZX_TEST: PASS]", "zx_test did not report [ZX_TEST: PASS]"),
    (b"Pipeline test: BUSYBOX PIPELINE OK",
     "init's `tr` pipeline did not produce BUSYBOX PIPELINE OK"),
]
SHELL_CHECKS = [
    (re.compile(rb"(?m)^INTERACTIVE_SHELL_TEST=42\r*$"),
     "shell arithmetic result INTERACTIVE_SHELL_TEST=42 not seen"),
    (re.compile(rb"(?m)^SHELL_PIPE_ZIRCON\r*$"),
     "shell pipeline result SHELL_PIPE_ZIRCON not seen"),
    (re.compile(rb"PID\s+PPID\s+ZX_KOID"),
     "/proc/zircon/processes header not seen"),
    (re.compile(rb"(?m)^BUSYBOX_SHELL_DONE_1337\r*$"),
     "final computed marker BUSYBOX_SHELL_DONE_1337 not seen"),
]


def suite_problems(out, is_aarch64=False):
    problems = []
    for name, tag, min_checks in SUITES:
        if is_aarch64 and name == "proc_test":
            min_checks = 40
        fail = re.search(rb"\[" + tag.encode() + rb": FAIL[^\r\n]*", out)
        if fail:
            problems.append(f"{name} reported failures: "
                            f"{fail.group(0).decode(errors='replace')}")
            continue
        m = re.search(rb"\[" + tag.encode() + rb": PASS (\d+)/(\d+)\]", out)
        if not m:
            problems.append(f"{name} did not print its [{tag}: PASS n/n] summary")
            continue
        passed, total = int(m.group(1)), int(m.group(2))
        if passed != total or total < min_checks:
            problems.append(f"{name} summary {passed}/{total} (need n/n with "
                            f"n >= {min_checks})")
        if f"{name} exit code: 0".encode() not in out:
            problems.append(f"{name} did not exit with status 0")
    return problems


def missing_checks(boot_out, shell_out, is_aarch64=False):
    missing = [msg for needle, msg in BOOT_CHECKS if needle not in boot_out]
    missing += suite_problems(boot_out, is_aarch64=is_aarch64)
    missing += [msg for rx, msg in SHELL_CHECKS if not rx.search(shell_out)]
    return missing


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("qemu_bin")
    parser.add_argument("boot_shim")
    parser.add_argument("zbi_image")
    parser.add_argument("--timeout", type=float, default=120.0)
    args = parser.parse_args()

    is_aarch64 = "aarch64" in args.qemu_bin
    if is_aarch64:
        cmd = [
            args.qemu_bin,
            "-machine", "virt,highmem=off",
            "-cpu", "cortex-a57",
            "-m", "1024M",
            "-smp", "2",
            "-nographic",
            "-no-reboot",
            "-kernel", args.boot_shim,
            "-initrd", args.zbi_image,
            "-append",
            "TERM=dumb kernel.halt-on-panic=true "
            "kernel.vdso.always_use_next=true userboot.next=bin/zircon_linux_init",
        ]
    else:
        cmd = [
            args.qemu_bin,
            "-machine", "q35,smbios-entry-point-type=32",
            "-cpu", "host,migratable=no,+invtsc",
            "-enable-kvm",
            "-m", "1024M",
            "-smp", "2",
            "-nographic",
            "-no-reboot",
            "-kernel", args.boot_shim,
            "-initrd", args.zbi_image,
            "-append",
            "TERM=dumb kernel.serial=legacy kernel.halt-on-panic=true "
            "kernel.vdso.always_use_next=true userboot.next=bin/zircon_linux_init",
        ]

    print(f"[verify_minimal] Launching QEMU: {' '.join(cmd)}", flush=True)
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT)

    output = b""
    sent_at_offset = None  # output offset when the shell commands were sent
    start = time.time()
    deadline = start + args.timeout
    stop_reason = f"timeout after {args.timeout:.0f}s"

    try:
        while time.time() < deadline:
            rlist, _, _ = select.select([proc.stdout], [], [], 0.2)
            if rlist:
                chunk = os.read(proc.stdout.fileno(), 65536)
                if not chunk:
                    stop_reason = f"QEMU exited (rc={proc.poll()})"
                    break
                sys.stdout.buffer.write(chunk)
                sys.stdout.buffer.flush()
                output += chunk

            if (b"[MINIMAL_ROOTFS: SHELL_READY]" in output and
                    SUITE_FAIL_RE.search(output)):
                stop_reason = "a conformance test reported failures"
                break

            if sent_at_offset is None and b"[MINIMAL_ROOTFS: SHELL_READY]" in output:
                sent_at_offset = len(output)
                time.sleep(0.2)
                proc.stdin.write(INTERACTIVE_SCRIPT)
                proc.stdin.flush()

            if sent_at_offset is not None and not missing_checks(
                    output, output[sent_at_offset:], is_aarch64=is_aarch64):
                stop_reason = "all milestones observed"
                break
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            proc.kill()

    elapsed = time.time() - start
    print(f"\n[verify_minimal] Stopped after {elapsed:.1f}s: {stop_reason}", flush=True)
    if sent_at_offset is None:
        failures = ["init never printed [MINIMAL_ROOTFS: SHELL_READY]; no "
                    "interactive commands were sent"]
        failures += [msg for needle, msg in BOOT_CHECKS if needle not in output]
        failures += suite_problems(output, is_aarch64=is_aarch64)
    else:
        failures = missing_checks(output, output[sent_at_offset:], is_aarch64=is_aarch64)
    if failures:
        print("\n[verify_minimal] FAIL:", file=sys.stderr)
        for f in failures:
            print(f"  - {f}", file=sys.stderr)
        return 1

    print("\n================================================================")
    print("[verify_minimal] PASS: Zircon + Linux Shim + BusyBox Shell OK!")
    print("================================================================")
    return 0


if __name__ == "__main__":
    sys.exit(main())
